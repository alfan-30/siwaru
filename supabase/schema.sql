-- Satu absensi per orang per hari
create unique index if not exists attendance_nis_tanggal_uniq on public.attendance(nis, tanggal);
create index if not exists attendance_nis_tanggal_idx on public.attendance(nis, tanggal desc);
create index if not exists schedules_kelas_tanggal_idx on public.schedules(kelas, tanggal);

-- ===== Fungsi bantu peran (dipakai di RLS) =====
create or replace function public.current_jabatan()
returns text language sql stable security definer set search_path = public
as $$ select lower(jabatan) from public.profiles where id = auth.uid() $$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select coalesce(public.current_jabatan() in ('admin','administrator'), false) $$;

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = public
as $$ select coalesce(public.current_jabatan() in
  ('admin','administrator','guru','guru bk','gurubk','guru_mapel','guru mapel'), false) $$;

revoke all on function public.current_jabatan() from public;
revoke all on function public.is_admin() from public;
revoke all on function public.is_staff() from public;
grant execute on function public.current_jabatan() to authenticated;
grant execute on function public.is_admin() to authenticated;
grant execute on function public.is_staff() to authenticated;

-- ===== Profil otomatis saat registrasi =====
-- Registrasi publik HANYA bisa menghasilkan 'guru' atau 'siswa'.
-- Peran ditentukan server dari awalan NIP/NIS (12 = guru, 14 = siswa), bukan dari
-- data kiriman browser. Akun admin dibuat manual (lihat supabase/admin.sql).
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  v_nip text := coalesce(nullif(new.raw_user_meta_data->>'nip_nis',''), 'PENDING-' || replace(new.id::text,'-',''));
  v_jabatan text := case when v_nip like '12%' then 'guru' else 'siswa' end;
begin
  insert into public.profiles (id, nip_nis, nama, kelas, jabatan, no_tlp, alamat, jenis_kelamin, email)
  values (new.id, v_nip,
    coalesce(nullif(new.raw_user_meta_data->>'nama',''), split_part(new.email,'@',1)),
    case when v_jabatan = 'siswa' then nullif(new.raw_user_meta_data->>'kelas','') else null end,
    v_jabatan,
    new.raw_user_meta_data->>'no_tlp', new.raw_user_meta_data->>'alamat',
    new.raw_user_meta_data->>'jenis_kelamin', new.email);
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

-- ===== Login memakai NIP/NIS =====
-- Saat login, pengguna belum punya sesi sehingga tidak bisa membaca tabel profiles (RLS).
-- Fungsi ini hanya mengembalikan email untuk satu NIP/NIS yang diketik.
create or replace function public.email_for_login(p_nip text)
returns text language sql stable security definer set search_path = public
as $$ select email from public.profiles where nip_nis = p_nip limit 1 $$;
revoke all on function public.email_for_login(text) from public;
grant execute on function public.email_for_login(text) to anon, authenticated;

-- ===== Aturan absensi (dipaksa di server, tidak bisa dilewati lewat browser) =====
-- Guru dan siswa hanya bisa absen pukul 07:00 s/d 07:30 WIB. Pukul 07:31 sudah ditutup.
-- Nama, NIS/NIP, tanggal, dan jam selalu diisi server dari akun yang login.
create or replace function public.enforce_attendance_rules()
returns trigger language plpgsql set search_path = public
as $$
declare
  p public.profiles;
  sekarang timestamp := (now() at time zone 'Asia/Jakarta');
begin
  -- Tanpa login (mis. SQL Editor): lewati. Pengguna anon tetap ditolak oleh RLS.
  if auth.uid() is null or public.is_admin() then
    return new;
  end if;
  select * into p from public.profiles where id = auth.uid();
  if not found or lower(p.jabatan) not in ('guru','siswa') then
    raise exception 'Hanya guru dan siswa yang dapat melakukan absensi.';
  end if;
  if sekarang::time < time '07:00' or sekarang::time >= time '07:31' then
    raise exception 'Absensi ditutup. Absensi hanya dibuka pukul 07:00 sampai 07:30.';
  end if;
  new.nama_siswa := p.nama;
  new.nis := p.nip_nis;
  new.peran := lower(p.jabatan);
  new.tanggal := sekarang::date;
  new.waktu := date_trunc('second', sekarang)::time;
  new.dicatat_oleh := auth.uid();
  return new;
end; $$;
drop trigger if exists attendance_rules on public.attendance;
create trigger attendance_rules before insert on public.attendance
for each row execute function public.enforce_attendance_rules();

