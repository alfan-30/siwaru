create extension if not exists pgcrypto;

create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  nama_kelas text unique not null,
  created_at timestamptz not null default now()
);
create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  nama_mapel text unique not null,
  created_at timestamptz not null default now()
);
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nip_nis text unique not null,
  nama text not null,
  kelas text,
  jabatan text not null default 'siswa' check (lower(jabatan) in ('admin','administrator','guru','guru bk','gurubk','siswa','guru_mapel','guru mapel')),
  no_tlp text,
  alamat text,
  jenis_kelamin text,
  email text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.students (
  id bigint generated by default as identity primary key,
  nip_nis text unique not null,
  nama text not null,
  kelas text,
  no_tlp text,
  email text,
  alamat text,
  jenis_kelamin text,
  created_at timestamptz not null default now()
);
create table if not exists public.teachers (
  id bigint generated by default as identity primary key,
  nip_nis text unique not null,
  nama text not null,
  jabatan text default 'guru',
  no_tlp text,
  email text,
  alamat text,
  jenis_kelamin text,
  created_at timestamptz not null default now()
);
create table if not exists public.schedules (
  id bigint generated by default as identity primary key,
  kode_jadwal text unique,
  mata_pelajaran text not null,
  guru text,
  tanggal date,
  jam text,
  ruang text,
  kelas text,
  created_at timestamptz not null default now()
);
create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  nama_siswa text not null,
  nis text not null,
  mata_pelajaran text,
  tanggal date not null default current_date,
  waktu time,
  status text not null check (lower(status) in ('masuk','hadir','izin','alpa','terlambat','sakit')),
  alasan text,
  bukti_url text,
  dicatat_oleh uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
-- Kolom tambahan (aman dijalankan ulang): peran pencatat absensi (guru / siswa)
